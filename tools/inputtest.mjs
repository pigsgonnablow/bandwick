import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(120000); // software rendering on a busy machine can be slow
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && /Shader Error|WebGL|THREE\./.test(m.text())) errs.push(m.text().slice(0, 300)); });
await page.goto(`${process.env.URL ?? 'http://localhost:4173/index.html'}#w4471-128`);
await page.waitForSelector('.loading.done', { timeout: 120000 });
await page.waitForTimeout(800);
const cam = () => page.evaluate(() => { const c = window.__lw.view.cam; return { x: +c.target.x.toFixed(2), z: +c.target.z.toFixed(2), zoom: +c.zoom.toFixed(2), yaw: c.yawIndex }; });
const a = await cam();
await page.mouse.move(700, 450); await page.mouse.down(); await page.mouse.move(800, 500, { steps: 8 }); await page.mouse.up();
await page.waitForTimeout(600);
const b = await cam();
await page.mouse.wheel(0, -600); await page.waitForTimeout(1200);
const c = await cam();
await page.keyboard.press('e'); await page.waitForTimeout(800);
const d = await cam();
await page.mouse.click(720, 450); await page.waitForTimeout(400);
const pinned = await page.evaluate(() => window.__lw.snap.pinned);
await page.keyboard.press('3'); await page.waitForTimeout(300);
const speed = await page.evaluate(() => window.__lw.snap.speed);
await page.keyboard.press(' '); await page.waitForTimeout(300);
const paused = await page.evaluate(() => window.__lw.snap.paused);
await page.click('text=Winter'); await page.waitForTimeout(300);
const season = await page.evaluate(() => Math.floor((window.__lw.snap.minutes / 1440 / 12) % 4));
console.log(JSON.stringify({ start: a, afterDrag: b, afterZoomIn: c, afterRotate: d, pinned, speed, paused, season, errs }));
await browser.close();
